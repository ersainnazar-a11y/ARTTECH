const NEGATIONS = new Set(['не', 'ни', 'нет', 'без']);
const INTENSIFIERS = new Set(['очень', 'так', 'такой', 'такая', 'супер', 'безумно', 'совсем', 'ужасно', 'невероятно', 'страшно', 'сильно']);

export const normalize = (s: string) => s.toLowerCase().replace(/ё/g, 'е');

export function tokenize(text: string): string[] {
  return normalize(text).match(/[а-яa-z0-9-]+/g) ?? [];
}

/** совпадение по шаблону; шаблон из двух слов сверяется с парой токенов */
function matchAt(tokens: string[], i: number, pattern: string): number {
  const parts = normalize(pattern).split(' ');
  for (let k = 0; k < parts.length; k++) {
    const t = tokens[i + k];
    if (!t) return 0;
    const p = parts[k];
    const ok = p.endsWith('*') ? t.startsWith(p.slice(0, -1)) && t.length >= p.length - 1 : t === p;
    if (!ok) return 0;
  }
  return parts.length;
}

function findFirst(tokens: string[], patterns: string[]): string | null {
  for (let i = 0; i < tokens.length; i++)
    for (const p of patterns) if (matchAt(tokens, i, p)) return tokens[i];
  return null;
}

export interface TextHit { word: string; axes: Partial<Record<Axis, number>>; negated: boolean; boosted: boolean }

export interface TextAnalysis {
  valence: number; arousal: number; warmth: number; nostalgia: number; social: number; intimacy: number;
  timeOfDay: TimeOfDay | null; timeWord: string | null;
  season: Season | null; seasonWord: string | null;
  weather: Weather | null; weatherWord: string | null;
  motifs: { id: MotifId; word: string }[];
  sensory: Sensory;
  hits: TextHit[];
  confidence: number;
  tokens: string[];
}

export function analyzeTextRules(text: string): TextAnalysis {
  const tokens = tokenize(text);
  const sum: Record<Axis, number> = { v: 0, a: 0, w: 0, n: 0, s: 0, i: 0 };
  const hits: TextHit[] = [];

  for (let i = 0; i < tokens.length; i++) {
    for (const lex of LEXICON) {
      let len = 0;
      for (const p of lex.p) { len = matchAt(tokens, i, p); if (len) break; }
      if (!len) continue;
      const prev = tokens[i - 1], prev2 = tokens[i - 2];
      const negated = NEGATIONS.has(prev) || (INTENSIFIERS.has(prev) && NEGATIONS.has(prev2));
      const boosted = INTENSIFIERS.has(prev) || INTENSIFIERS.has(prev2);
      const k = boosted ? 1.5 : 1;
      const axes: Partial<Record<Axis, number>> = {};
      for (const ax of ['v', 'a', 'w', 'n', 's', 'i'] as Axis[]) {
        let val = lex[ax];
        if (!val) continue;
        // отрицание переворачивает валентность и гасит прочие оси
        val = negated ? (ax === 'v' ? -val * 0.8 : val * 0.25) : val;
        val *= k;
        sum[ax] += val;
        axes[ax] = val;
      }
      hits.push({ word: tokens.slice(i, i + len).join(' '), axes, negated, boosted });
      break;
    }
  }

  const pick = <T,>(table: [T, string[]][]): [T | null, string | null] => {
    // берём то, что встречается в тексте раньше всего упомянутым — по порядку таблицы с первым найденным словом
    let best: [T | null, string | null, number] = [null, null, Infinity];
    for (const [id, pats] of table) {
      for (let i = 0; i < tokens.length && i < best[2]; i++)
        for (const p of pats) if (matchAt(tokens, i, p)) { best = [id, tokens[i], i]; break; }
    }
    return [best[0], best[1]];
  };

  const [timeOfDay, timeWord] = pick(TIME);
  const [season, seasonWord] = pick(SEASON);
  const [weather, weatherWord] = pick(WEATHER);

  const motifs: { id: MotifId; word: string }[] = [];
  for (const [id, pats] of MOTIF_TRIGGERS) {
    const w = findFirst(tokens, pats);
    if (w) motifs.push({ id, word: w });
  }

  const sensory: Sensory = { light: [], sounds: [], smells: [], textures: [] };
  for (const [kind, pats] of SENSORY) {
    for (let i = 0; i < tokens.length; i++)
      for (const p of pats) if (matchAt(tokens, i, p) && !sensory[kind].includes(tokens[i])) { sensory[kind].push(tokens[i]); break; }
  }

  const t = Math.tanh;
  return {
    valence: t(sum.v / 2.2),
    arousal: clamp(0.42 + 0.5 * t(sum.a / 2)),
    warmth: clamp(0.5 + 0.5 * t(sum.w / 2)),
    nostalgia: clamp(t(Math.max(0, sum.n) / 1.6)),
    social: clamp(0.35 + 0.6 * t(sum.s / 2)),
    intimacy: clamp(0.15 + 0.85 * t(Math.max(0, sum.i) / 1.6)),
    timeOfDay, timeWord, season, seasonWord, weather, weatherWord,
    motifs, sensory, hits,
    confidence: clamp(hits.length / 6) * clamp(tokens.length / 12, 0.4, 1),
    tokens,
  };
}

/** самое «нагруженное» предложение — кандидат в рукописную подпись (собственные слова автора) */
export function pickCaption(text: string): string {
  const sentences = text.split(/(?<=[.!?…])\s+|\n+/).map(s => s.trim()).filter(s => s.length > 3);
  if (!sentences.length) return '';
  let best = sentences[0], bestScore = -1;
  for (const s of sentences) {
    const a = analyzeTextRules(s);
    const score = a.hits.reduce((acc, h) => acc + Object.values(h.axes).reduce((x, y) => x + Math.abs(y ?? 0), 0), 0) - Math.max(0, s.length - 70) * 0.05;
    if (score > bestScore) { bestScore = score; best = s; }
  }
  best = best.replace(/[.!…]+$/, '');
  if (best.length > 64) {
    const cut = best.slice(0, 62);
    best = cut.slice(0, cut.lastIndexOf(' ')) + '…';
  }
  return best.charAt(0).toLowerCase() + best.slice(1);
}
